def seed_banana_fact(db: Session):

    existing = {row.content for row in db.query(BananaFact.content).all()}

    if existing == set(DEFAULT_FACTS):
        return

    db.query(BananaFact).delete()

    for content in DEFAULT_FACTS:

        db.add(BananaFact(content=content))

    db.commit()

    print(f"banana_fact 테이블을 {len(DEFAULT_FACTS)}개 행으로 갱신했습니다.")
